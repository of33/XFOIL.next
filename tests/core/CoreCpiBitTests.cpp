// File: tests/core/CoreCpiBitTests.cpp
// bit/provenance proof for the canonical CPI producer chain. Compares the
// CPI generated by the core (naca4/pangen/ggCalc/specAlpha ->
// SpecPointResult.cp) against the complete Fortran oracle
// tests/data/core-cpi-reference/cpi_reference.txt (harness
// tests/fortran-reference/harnesses/cpi/cpi_harness.f, built canonically
// with -fdefault-real-8 -fdefault-double-8; unqualified REAL = REAL(8) =
// C++ double).
//
// Compared values (per assignment):
// C0 panel/operating state: N, X(I), Y(I), ALFA, MINF
// C1 inviscid solution vectors: GAM via QINV inputs
// C2 inputs to the Cp computation: QINV(I)
// C3 CPI immediately after computation (SpecPointResult.cp)
// bit comparison via IEEE-754 bits (std::bit_cast<uint64_t>); no
// tolerance increase. On deviation, the first differing element is
// reported with bits and ULP distance.

